import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:5173/#dunia', { waitUntil: 'networkidle' });
  await page.waitForFunction(() => !document.getElementById('btn-title-play').disabled);
  assert.equal(await page.evaluate(() => location.hash), '');
  assert.equal(await page.locator('nav').count(), 0);
  await page.screenshot({ path: 'artifacts/arcade-menu.png' });
  await page.locator('#btn-title-play').click();
  await page.keyboard.down('d'); await page.waitForTimeout(400); await page.keyboard.up('d');
  assert.ok(await page.evaluate(() => game.player.x > 150));
  await page.keyboard.press('w');
  assert.ok(await page.evaluate(() => game.player.vy < 0));
  await page.keyboard.press('2');
  assert.equal(await page.evaluate(() => game.player.weaponIdx), 1);
  await page.keyboard.press('j');
  await page.keyboard.press('Escape');
  const frozen = await page.evaluate(() => JSON.stringify({ p: game.player, score: game.score, enemies: game.enemies }));
  await page.waitForTimeout(250);
  assert.equal(await page.evaluate(() => JSON.stringify({ p: game.player, score: game.score, enemies: game.enemies })), frozen);
  await page.locator('#btn-title-play').click();
  assert.equal(await page.evaluate(() => game.paused), false);
  await page.locator('#btn-open-map').click();
  await page.locator('[data-map-idx="3"]').click();
  await page.locator('#btn-map-launch').click();
  assert.equal(await page.evaluate(() => game.stageIdx), 3);
  await page.waitForTimeout(1500);
  await page.screenshot({ path: 'artifacts/arcade-game.png' });
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  assert.equal(await page.evaluate(() => game.paused), true);
  await page.locator('#btn-title-codex').click();
  assert.equal(await page.locator('#codex-grid > div').count(), 8);
  await page.locator('#btn-codex-toggle-art').click();
  await page.locator('#btn-close-codex').click();
  assert.equal(await page.evaluate(() => game.paused), true);
  await page.locator('#btn-audio-toggle').click();
  assert.equal(await page.evaluate(() => localStorage.getItem('vincy-muted')), 'true');
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  mobile.on('pageerror', e => errors.push(e.message));
  await mobile.goto('http://127.0.0.1:5173', { waitUntil: 'networkidle' });
  await mobile.waitForFunction(() => !document.getElementById('btn-title-play').disabled);
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await mobile.screenshot({ path: 'artifacts/arcade-mobile-menu.png' });
  await mobile.locator('#btn-title-play').tap();
  await mobile.locator('#pad-jump').tap();
  assert.ok(await mobile.evaluate(() => game.player.jumpsLeft < 2));
  await mobile.locator('#btn-mobile-weapon').tap();
  assert.equal(await mobile.evaluate(() => game.player.weaponIdx), 1);
  await mobile.locator('#pad-shoot').tap();
  assert.ok(await mobile.locator('footer').evaluate(e => e.getBoundingClientRect().bottom <= innerHeight + 1));
  assert.ok(await mobile.locator('header').evaluate(e => e.getBoundingClientRect().top >= 0));
  await mobile.screenshot({ path: 'artifacts/arcade-mobile-game.png' });
  await mobile.setViewportSize({ width: 844, height: 390 });
  await mobile.locator('#btn-pause-menu').tap();
  await mobile.screenshot({ path: 'artifacts/arcade-landscape.png' });
  await mobile.locator('#btn-title-play').tap();
  assert.ok(await mobile.evaluate(() => !game.paused));
  const broken = await mobile.locator('img').evaluateAll(imgs => imgs.filter(i => !i.complete || !i.naturalWidth).map(i => i.src));
  assert.deepEqual(broken, []);
  assert.deepEqual(errors, []);
  console.log('PASS: game menu, movement, shooting, pause/resume, stage selection, codex, mute, portrait/landscape, no broken images or browser errors.');
} finally { await browser.close(); }
